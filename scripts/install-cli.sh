#!/usr/bin/env bash
# Install the `marque` CLI as a wrapper that launches the GUI detached
# from the calling terminal, then returns immediately.
#
# Run after `pnpm tauri build` (or `pnpm tauri build --no-bundle`).
# Linux only.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TARGET_DIR="${MARQUE_INSTALL_DIR:-$HOME/.local/bin}"
WRAPPER="$TARGET_DIR/marque"

RAW_BINARY="$ROOT/src-tauri/target/release/marque"
DEBUG_BINARY="$ROOT/src-tauri/target/debug/marque"

mkdir -p "$TARGET_DIR"

if [[ -x "$RAW_BINARY" || -x "$DEBUG_BINARY" ]]; then
  bin="$RAW_BINARY"
  [[ -x "$bin" ]] || bin="$DEBUG_BINARY"
  # Spawn detached, redirect output, disown.
  cat > "$WRAPPER" <<EOF
#!/usr/bin/env bash
# Auto-generated by marque/scripts/install-cli.sh
nohup "$bin" "\$@" >/dev/null 2>&1 &
disown >/dev/null 2>&1 || true
EOF
  source_kind="binary ($bin)"
else
  echo "error: no built marque binary found." >&2
  echo "  build first with:  pnpm tauri build" >&2
  exit 1
fi

chmod +x "$WRAPPER"
echo "installed wrapper: $WRAPPER"
echo "  → $source_kind"

case ":$PATH:" in
  *":$TARGET_DIR:"*)
    echo "ready: run 'marque FILE.md' or 'marque DIR/'"
    ;;
  *)
    echo
    echo "warning: $TARGET_DIR is not on PATH"
    echo "  add this to your shell profile:"
    echo "    export PATH=\"\$HOME/.local/bin:\$PATH\""
    echo "  or for fish:"
    echo "    set -Ux fish_user_paths \$HOME/.local/bin \$fish_user_paths"
    ;;
esac
